#!/usr/bin/env python3
"""Generate typed consumers from the frozen bridge contract schemas.

Reads packages/bridge-contracts/schemas/*.schema.json and regenerates:
  - src/bridge_contracts/_generated.py  (embedded schemas + contract version)
  - generated/bridge.types.ts           (TypeScript types for bridge consumers)
  - generated/contract-manifest.json    (sha256 manifest enforcing freeze sync)

Usage:
  python3 scripts/generate.py           # regenerate
  python3 scripts/generate.py --check   # fail if any output is stale

Standard library only.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMAS_DIR = ROOT / "schemas"
SRC_DIR = ROOT / "src" / "bridge_contracts"
GENERATED_DIR = ROOT / "generated"

CONTRACT_VERSION = "0.1.0"
OPENAPI_REL = Path("docs/05-contracts/bridge.openapi.yaml")

SCHEMA_FILES = ["bridge-api.schema.json", "bridge-events.schema.json"]


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_defs() -> dict:
    defs: dict = {}
    for name in SCHEMA_FILES:
        doc = json.loads((SCHEMAS_DIR / name).read_text(encoding="utf-8"))
        for key, schema in doc.get("$defs", {}).items():
            if key in defs:
                raise SystemExit("duplicate $def name: %s" % key)
            defs[key] = schema
    return defs


# --- TypeScript emission ----------------------------------------------------

def ts_type(schema: dict, defs: dict, depth: int = 0) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    t = schema.get("type")
    if isinstance(t, list):
        parts = [ts_simple_type(x, schema, defs, depth) for x in t]
        return " | ".join(parts)
    return ts_simple_type(t, schema, defs, depth)


def ts_simple_type(t, schema: dict, defs: dict, depth: int) -> str:
    if t == "string":
        return "string"
    if t == "integer" or t == "number":
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        items = schema.get("items", {})
        return "Array<%s>" % ts_type(items, defs, depth + 1)
    if t == "object":
        props = schema.get("properties")
        if not props:
            return "Record<string, unknown>"
        return ts_inline_object(schema, defs, depth)
    return "unknown"


def ts_inline_object(schema: dict, defs: dict, depth: int) -> str:
    required = set(schema.get("required", []))
    indent = "  " * (depth + 1)
    lines = ["{"]
    for name, prop in schema.get("properties", {}).items():
        opt = "" if name in required else "?"
        lines.append("%s%s%s: %s;" % (indent, name, opt, ts_type(prop, defs, depth + 1)))
    lines.append("%s}" % ("  " * depth))
    return "\n".join(lines)


def emit_ts(defs: dict) -> str:
    lines = [
        "// Generated from packages/bridge-contracts/schemas/*.schema.json — do not edit by hand.",
        "// Regenerate with: python3 scripts/generate.py  (contract v%s)" % CONTRACT_VERSION,
        "",
    ]
    for name in sorted(defs):
        schema = defs[name]
        resolved = dict(schema)
        while "$ref" in resolved:
            resolved = defs[resolved["$ref"].split("/")[-1]]
        if "enum" in resolved or "const" in resolved:
            lines.append("export type %s = %s;" % (name, ts_type(resolved, defs)))
        elif resolved.get("type") == "object" and resolved.get("properties"):
            required = set(resolved.get("required", []))
            lines.append("export interface %s {" % name)
            for prop_name, prop in resolved["properties"].items():
                opt = "" if prop_name in required else "?"
                lines.append("  %s%s: %s;" % (prop_name, opt, ts_type(prop, defs, 1)))
            lines.append("}")
        else:
            lines.append("export type %s = %s;" % (name, ts_type(resolved, defs)))
        lines.append("")
    return "\n".join(lines)


# --- Python embedding -------------------------------------------------------

GENERATED_PY_TEMPLATE = '''"""Embedded frozen schemas. Generated by scripts/generate.py — do not edit by hand."""

CONTRACT_VERSION = %(version)r
OPENAPI_VERSION = %(openapi)r

SCHEMAS = %(schemas)s
'''


def emit_generated_py(defs: dict, openapi_version: str) -> str:
    import pprint

    return GENERATED_PY_TEMPLATE % {
        "version": CONTRACT_VERSION,
        "openapi": openapi_version,
        "schemas": pprint.pformat(defs, width=100, sort_dicts=False),
    }


def read_openapi_version() -> str:
    from pathlib import Path as P

    repo_root = ROOT.parent.parent
    text = (repo_root / str(OPENAPI_REL)).read_text(encoding="utf-8")
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("version:"):
            return stripped.split(":", 1)[1].strip()
    raise SystemExit("openapi version not found in %s" % OPENAPI_REL)


def build_manifest(outputs: dict) -> dict:
    schemas = {name: sha256_file(SCHEMAS_DIR / name) for name in SCHEMA_FILES}
    return {
        "contractVersion": CONTRACT_VERSION,
        "openapiSpec": str(OPENAPI_REL),
        "openapiVersion": read_openapi_version(),
        "schemas": schemas,
        "generated": {name: hashlib.sha256(content.encode("utf-8")).hexdigest() for name, content in outputs.items()},
    }


def main(argv) -> int:
    check = "--check" in argv
    defs = load_defs()
    openapi_version = read_openapi_version()

    ts_content = emit_ts(defs)
    py_content = emit_generated_py(defs, openapi_version)
    outputs = {
        "generated/bridge.types.ts": ts_content,
        "src/bridge_contracts/_generated.py": py_content,
    }
    manifest = build_manifest(outputs)
    manifest_text = json.dumps(manifest, indent=2) + "\n"
    outputs["generated/contract-manifest.json"] = manifest_text

    targets = {
        GENERATED_DIR / "bridge.types.ts": ts_content,
        SRC_DIR / "_generated.py": py_content,
        GENERATED_DIR / "contract-manifest.json": manifest_text,
    }
    stale = []
    for path, content in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    if check and stale:
        print("stale generated files (run scripts/generate.py):")
        for name in stale:
            print("  " + name)
        return 1
    if not check:
        if stale:
            print("regenerated: " + ", ".join(stale))
        else:
            print("generated outputs already current (contract v%s)" % CONTRACT_VERSION)
    else:
        print("generated outputs current (contract v%s)" % CONTRACT_VERSION)
    if openapi_version != CONTRACT_VERSION:
        print(
            "WARNING: openapi %s != contract %s; freeze sync broken"
            % (openapi_version, CONTRACT_VERSION)
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
